/**
 * Fonction utilitaire pour récupérer les questions par mode
 */
export const getQuestionsByModes = (modes: NheMode[]): NheQuestion[] => {
  return neverHaveIEverQuestions.filter((q) => modes.includes(q.mode));
};

/**
 * Fonction utilitaire pour mélanger un tableau (algorithme Fisher-Yates)
 */
export const shuffleQuestions = (questions: NheQuestion[]): NheQuestion[] => {
  const shuffled = [...questions];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
};
